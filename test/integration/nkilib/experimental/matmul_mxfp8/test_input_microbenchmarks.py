"""MXFP8 matmul input method microbenchmarks.

Compares different input preparation methods across representative
matrix shapes to measure their relative performance:

1. Prequantized MXFP8 swizzled (both LHS/RHS pre-quantized + swizzled)
2. Preswizzled BF16 (both LHS/RHS swizzled BF16, no spill reload)
3. DMA gather transpose (unswizzled BF16 with DGT tile_m=128)
4. PE swizzle 1x32 (unswizzled BF16 with PE swizzle, quant_scheme=1x32)
5. LHS BF16 wrapX PE swizzle + RHS wrapX prequantized (hybrid: LHS unswizzled
   wrapX PE swizzle, RHS pre-quantized MXFP8 wrapX-swizzled)
6. LHS BF16 1x32 PE swizzle + RHS 1x32 prequantized (hybrid: LHS unswizzled
   1x32 PE swizzle, RHS pre-quantized MXFP8 1x32-swizzled)
7. LHS BF16 DGT + RHS wrapX prequantized (hybrid: LHS unswizzled DMA
   gather-transpose, RHS pre-quantized MXFP8 wrapX-swizzled)

These tests are tagged with "model" to run in the model phase of the pipeline.
"""

import numpy as np
import pytest
from nkilib_src.nkilib.experimental.matmul_mxfp8 import matmul_mxfp8_generic_kernel
from nkilib_src.nkilib.experimental.matmul_mxfp8.matmul_mxfp8_torch import matmul_mxfp8_torch_ref

