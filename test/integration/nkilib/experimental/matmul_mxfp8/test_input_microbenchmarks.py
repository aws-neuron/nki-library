@pytest_test_metadata(name="Matmul Input Method Microbenchmarks", tags=["model"])
@pytest_marks(["generic_matmul_mxfp8_perf", "mx", "mxfp8", "model", "optimal"])
@pytest.mark.platforms(exclude=[common_dataclasses.Platforms.TRN1, common_dataclasses.Platforms.TRN2])
class TestMatmulMxfp8InputMethodMicrobenchmarks:
    """Microbenchmarks comparing matmul input preparation methods.

    Each test method exercises one input method across the benchmark shapes,
    measuring end-to-end matmul performance including data loading overhead.
    """

    def _run_test(self, test_manager, conf, platform_target):
        if not platform_target.is_trn3():
            pytest.skip("MX is only supported on TRN3.")

        compiler_args = common_dataclasses.CompilerArgs(
            logical_nc_config=2 if conf.run_with_lnc2 else 1,
            platform_target=platform_target,
        )

        test_manager.collector.set_kernel_params(conf.to_metrics_dict())
        output_dtype = get_output_dtype(conf)

        def input_generator(test_config):
            return build_matmul_inputs(conf)

        def output_tensors(kernel_input):
            return {"out": np.zeros((conf.M, conf.N), dtype=output_dtype)}

        framework = UnitTestFramework(
            test_manager=test_manager,
            kernel_entry=matmul_mxfp8_generic_kernel.matmul_mxfp8,
            torch_ref=matmul_mxfp8_torch_ref,
            kernel_input_generator=input_generator,
            output_tensor_descriptor=output_tensors,
        )
        framework.run_test(
            test_config=None,
            compiler_args=compiler_args,
            custom_comparator=_mxfp8_comparator(conf, output_dtype, False),
        )

    # --- Method 1: Prequantized MXFP8 ---

    @pytest.mark.parametrize("conf", GRID_PREQUANTIZED)
    def test_prequantized(self, test_manager, conf, platform_target):
        self._run_test(test_manager, conf, platform_target)

    # --- Method 2: Preswizzled BF16 ---

    @pytest.mark.parametrize("conf", GRID_PRESWIZZLED)
    def test_preswizzled(self, test_manager, conf, platform_target):
        self._run_test(test_manager, conf, platform_target)

    # --- Method 3: DMA Gather Transpose ---

    @pytest.mark.parametrize("conf", GRID_DGT)
    def test_dma_gather_transpose(self, test_manager, conf, platform_target):
        self._run_test(test_manager, conf, platform_target)

    # --- Method 4: PE Swizzle 1x32 ---

    @pytest.mark.parametrize("conf", GRID_PE_SWIZZLE_1X32)
    def test_pe_swizzle_1x32(self, test_manager, conf, platform_target):
        self._run_test(test_manager, conf, platform_target)

    # --- Method 5: LHS BF16 wrapX PE Swizzle + RHS wrapX Prequantized ---

    @pytest.mark.parametrize("conf", GRID_LHS_WRAPX_PE_RHS_WRAPX_PREQUANT)
    def test_lhs_wrapx_pe_swizzle_rhs_wrapx_prequantized(self, test_manager, conf, platform_target):
        self._run_test(test_manager, conf, platform_target)

    # --- Method 6: LHS BF16 1x32 PE Swizzle + RHS 1x32 Prequantized ---

    @pytest.mark.parametrize("conf", GRID_LHS_1X32_PE_RHS_1X32_PREQUANT)
    def test_lhs_1x32_pe_swizzle_rhs_1x32_prequantized(self, test_manager, conf, platform_target):
        self._run_test(test_manager, conf, platform_target)

    # --- Method 7: LHS BF16 DGT + RHS wrapX Prequantized ---

    @pytest.mark.parametrize("conf", GRID_LHS_DGT_RHS_WRAPX_PREQUANT)
    def test_lhs_dgt_rhs_wrapx_prequantized(self, test_manager, conf, platform_target):
        self._run_test(test_manager, conf, platform_target)
